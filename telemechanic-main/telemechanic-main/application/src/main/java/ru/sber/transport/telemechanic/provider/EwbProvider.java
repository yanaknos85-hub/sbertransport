package ru.sber.transport.telemechanic.provider;

import ru.sber.transport.telemechanic.FirstTitleCreateRequestMessage;

/**
 * Интерфейс провайдера для обработки и сохранения данных первого титула ЭПЛ (электронный путевой лист).
 * <p>Предоставляет методы для сохранения информации о ЭПЛ на основе сообщений из Kafka.</p>
 */
public interface EwbProvider {
    
    /**
     * Сохраняет данные первого титула ЭПЛ на основе полученного сообщения.
     * <p>Обрабатывает информацию о перевозке, включая данные водителя, транспортного средства,
     * сроки перевозки и сформированный файл титула с цифровой подписью.</p>
     *
     * @param message сообщение о создании первого титула ЭПЛ, содержащее полные данные о перевозке и документе
     */
    void save(FirstTitleCreateRequestMessage message);
}
